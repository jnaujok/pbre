import base64
import json

from pbre.cli import main

BLOB = bytes.fromhex("089601120774657374696e671a03089601")


def run(capsys, *args):
    rc = main(list(args))
    out = capsys.readouterr()
    return rc, out.out, out.err


def test_decode_raw(tmp_path, capsys):
    p = tmp_path / "m.bin"
    p.write_bytes(BLOB)
    rc, out, _ = run(capsys, str(p), "--no-prompt")
    assert rc == 0
    assert '2 field_2: string = "testing"' in out
    assert "3 field_3: Field3 {" in out


def test_decode_hex_and_base64(tmp_path, capsys):
    h = tmp_path / "m.hex"
    h.write_text(" ".join(f"{b:02x}" for b in BLOB) + "\n")
    rc, out, _ = run(capsys, "decode", str(h), "--no-prompt")
    assert "field_1: int32 = 150" in out
    b = tmp_path / "m.b64"
    b.write_text(base64.b64encode(BLOB).decode())
    rc, out, _ = run(capsys, "decode", "-f", "base64", str(b), "--no-prompt")
    assert "field_1: int32 = 150" in out


def test_json(tmp_path, capsys):
    p = tmp_path / "m.bin"
    p.write_bytes(BLOB)
    rc, out, _ = run(capsys, "decode", "--json", str(p))
    data = json.loads(out)
    assert data[1]["value"] == "testing"


def test_proto_command(tmp_path, capsys):
    p = tmp_path / "m.bin"
    p.write_bytes(BLOB)
    out_path = tmp_path / "out.proto"
    rc, _, err = run(capsys, "proto", str(p), "-m", "Thing", "--package", "a.b", "-o", str(out_path), "-H", "1=uint32:id")
    text = out_path.read_text()
    assert "message Thing {" in text
    assert "package a.b;" in text
    assert "uint32 id = 1;" in text


def test_decode_writes_proto(tmp_path, capsys):
    p = tmp_path / "m.bin"
    p.write_bytes(BLOB)
    rc, out, _ = run(capsys, "decode", str(p), "--proto", "-")
    assert 'syntax = "proto3";' in out


def test_delimited_and_grpc(tmp_path, capsys):
    p = tmp_path / "s.bin"
    p.write_bytes(bytes([len(BLOB)]) + BLOB + bytes([2, 0x08, 0x01]))
    rc, out, _ = run(capsys, "decode", "--delimited", str(p), "--no-prompt")
    assert "--- message 2 ---" in out
    g = tmp_path / "g.bin"
    g.write_bytes(b"\x00" + len(BLOB).to_bytes(4, "big") + BLOB)
    rc, out, _ = run(capsys, "decode", "--grpc", str(g), "--no-prompt")
    assert '"testing"' in out


def test_invalid_input(tmp_path, capsys):
    p = tmp_path / "bad.bin"
    p.write_bytes(b"\x0a\x05ab")
    try:
        main(["decode", str(p), "--no-prompt"])
    except SystemExit as e:
        assert "not a valid protobuf message" in str(e)
    else:
        raise AssertionError("expected failure")


def test_interactive_offer(tmp_path, capsys, monkeypatch):
    p = tmp_path / "m.bin"
    p.write_bytes(BLOB)
    monkeypatch.setattr("pbre.cli._interactive", lambda: True)
    answers = iter(["y", str(tmp_path / "x.proto")])
    monkeypatch.setattr("builtins.input", lambda prompt="": next(answers))
    rc, out, err = run(capsys, "decode", str(p))
    assert (tmp_path / "x.proto").read_text().startswith("// Generated by pbre")
