"""Render an inferred :class:`MessageSchema` as a .proto file."""

from __future__ import annotations

from typing import List, Optional

from .schema import FieldSchema, MessageSchema, SCALAR_TYPES
from .wire import RESERVED_RANGE

PACKABLE = SCALAR_TYPES


def generate_proto(
    schema: MessageSchema,
    syntax: Optional[str] = None,
    package: Optional[str] = None,
    sample_count: int = 1,
    comments: bool = True,
) -> str:
    """Return .proto source for ``schema``.

    ``syntax`` defaults to proto3, falling back to proto2 when the data uses
    groups (which proto3 cannot express).
    """
    if syntax is None:
        syntax = "proto2" if schema.uses_groups() else "proto3"
    if syntax not in ("proto2", "proto3"):
        raise ValueError("syntax must be proto2 or proto3")
    if syntax == "proto3" and schema.uses_groups():
        raise ValueError("the data contains groups, which require proto2 syntax")

    lines: List[str] = []
    if comments:
        lines.append(
            f"// Generated by pbre from {sample_count} sample{'s' if sample_count != 1 else ''}."
        )
        lines.append("// Field names and types are inferred from the wire data; review them.")
    lines.append(f'syntax = "{syntax}";')
    lines.append("")
    if package:
        lines.append(f"package {package};")
        lines.append("")
    _emit_message(schema, lines, 0, syntax, comments)
    return "\n".join(lines) + "\n"


def _emit_message(msg: MessageSchema, lines: List[str], depth: int, syntax: str, comments: bool):
    ind = "  " * depth
    lines.append(f"{ind}message {msg.name} {{")
    _emit_body(msg, lines, depth + 1, syntax, comments)
    lines.append(f"{ind}}}")


def _emit_body(msg: MessageSchema, lines, depth, syntax, comments):
    ind = "  " * depth
    nested: List[MessageSchema] = []
    for f in msg.sorted_fields():
        if f.number in RESERVED_RANGE:
            # protoc refuses to declare these numbers. Leave the field out so
            # the file still compiles; parsers keep it as an unknown field.
            lines.append(
                f"{ind}// field {f.number} omitted: 19000-19999 is reserved for the "
                "protobuf implementation and cannot be declared"
            )
            continue
        if comments:
            for note in f.notes:
                lines.append(f"{ind}// {note}")
        label = _label(f, syntax)
        if f.type == "group":
            assert f.message is not None
            lines.append(f"{ind}{label}group {f.message.name} = {f.number} {{")
            _emit_body(f.message, lines, depth + 1, syntax, comments)
            lines.append(f"{ind}}}")
            continue
        type_name = f.message.name if f.type == "message" and f.message else f.type
        if f.message is not None:
            nested.append(f.message)
        opts = _options(f, syntax)
        line = f"{ind}{label}{type_name} {f.name} = {f.number}{opts};"
        if comments and f.samples:
            line += "  // e.g. " + ", ".join(f.samples)
        lines.append(line)
    for m in nested:
        lines.append("")
        _emit_message(m, lines, depth, syntax, comments)


def _label(f: FieldSchema, syntax: str) -> str:
    if f.repeated:
        return "repeated "
    if syntax == "proto2":
        return "optional "
    if f.default_seen and f.type != "message":
        # proto3 drops zero/empty values unless the field has explicit presence
        return "optional "
    return ""


def _options(f: FieldSchema, syntax: str) -> str:
    if not f.repeated or f.type not in PACKABLE or f.packed is None:
        return ""
    if syntax == "proto3" and not f.packed:
        return " [packed = false]"
    if syntax == "proto2" and f.packed:
        return " [packed = true]"
    return ""
